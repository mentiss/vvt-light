// Clés de faction d'Influence : celles de factions.js, plus `inquisition`. La « Imperial Fleet »
// du chapitre Patron est la faction Imperial Navy des personnages (clé `imperial_navy`).
// influence (Faveurs, Handicaps, Fonctions) :
//   { faction: n }                       : valeur fixe ;
//   { choose: [factions], value: n }     : une faction au choix parmi la liste ;
//   { choose: 'any' | 'gm', count, value, note? } : `count` factions au choix du groupe ('any')
//                                          ou du MJ ('gm') ; `note` précise laquelle (ennemi…) ;
//   { byPatronFaction: { faction: influence } } : valeur selon la faction du Patron.
// payment : décalage du Grade de solde (Opulent +1, Avare −1).
// tableNames : autres noms donnés à la même entrée dans les tables d10 des Fonctions.
// DUTY_TABLES / ORDO_TABLES : listes de 10 clés, index 0 = résultat 1 du d10.
//
// À relire :
// - Correspondances de tableNames déduites (le livre ne les énonce pas) : Exercitium
//   Administratum / Mechanicus / Militarum / Religio / Inquisitionis / Auriga → les six centres de
//   formation ; Sanctum Archivium → Censorium de l'Administratum ; Sanctum Augmetica → Baie
//   augmétique ; Sanctum Medicae → Installation médicae ; Sanctum Munitorum → Dépôt du Munitorum ;
//   Servitor Squad → Clade de serviteurs ; Special Weaponist → Spécialiste des armes ; Psyker
//   Hunter (Handicap) → Chasseur de sorcières. Sûres : Sanctum Null = Sanctum nul, Sanctum
//   Religio = Sanctuaire ecclésiastique (texte identique), Ideologue = Idealogue Crusader.
// - Astérisques divergents entre tables et listes : Exercitium Militarum* (Centre d'entraînement
//   martial sans Influence dans la liste), Vigilite Vanguard* (pas d'Influence dans la liste),
//   Known Meddler, Registered Trader, Conveyance Commander avec ou sans *. L'influence suit la liste.
// - « Militarum Inspectorate » (Handicap des tables) : aucune description dans le livre, summary null.
// - Exige la discrétion : pas d'Influence dans CORE ; les fiches IGMG précisent « −1 Influence
//   avec l'Administratum ou l'Inquisition, au choix du MJ » : repris en optionnel.
// - Influence en plus de certaines Fonctions (Astropathe, Officier supérieur, Commandant de port,
//   Cerveau criminel, Maître de guilde) : identique à celle de leur Faveur gratuite ; lu comme une
//   seule et même prime (non cumulée), à confirmer.
// - Retirés, non définis dans aucun livre : « Auto-Seance* » (Faveur Malleus radicale, d10 = 1) et
//   « Xenogenetics » (Handicap Xenos radical, d10 = 10) : case laissée à null dans ORDO_TABLES.
// - « Utter Purity » (Handicap) : défini seulement sur la fiche de Konstan Serranus (IGMG p.71),
//   repris en source igmg. « Heretek » (fiche de Thracius) rattaché à Lien hérétek.
// - IPG p.25 : chaque Ordo donne une Faveur de Philosophie (colonne Puritain ou Radical) en plus
//   d'Autorité sans limite, puis jusqu'à 2 Faveurs ; le relevé disait « jusqu'à 2 » seulement.
// - Ksenia Baek citée sous l'Ordo Malleus (IPG p.27) mais Ordo Hereticus sur sa fiche (IGMG p.62).
// - Spécialisations des centres de formation citées telles quelles (Awareness (Sound), Intuition
//   (People), Lore (Common), Range (Long Guns), « Pilot ») : rattachement à skills.js à faire
//   selon la spec §6 (Ouïe, Humains…) ; « Savoir (Commun) » sans équivalent connu.
